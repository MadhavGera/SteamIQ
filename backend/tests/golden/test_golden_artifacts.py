"""
Golden Artifact Regression Tests — Phase 7.

Validates stability and reproducibility of recommendations generated by registered
model artifacts over 50 fixed user library histories.

Decorated with @pytest.mark.artifacts; automatically skips in CI or lightweight
environments when full artifact directories are absent.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from core.config import settings
from recsys.config import get_recsys_config
from recsys.inference import RecommenderService


def _artifacts_present() -> bool:
    data_dir = settings.resolved_recsys_data_dir
    artifacts_dir = data_dir / "artifacts"
    if not artifacts_dir.exists():
        return False
    # Check for two tower clean artifact
    tt_clean_dirs = list(artifacts_dir.glob("recsys_two_tower_clean/*"))
    return len(tt_clean_dirs) > 0


@pytest.mark.artifacts
def test_golden_artifact_reproducibility():
    """
    Evaluates 50 fixed, diverse user library histories against the production
    recsys_two_tower_clean model.
    Asserts top-10 stability and valid score bounds.
    """
    if not _artifacts_present():
        pytest.skip("Recommender model artifacts not found in local environment.")

    service = RecommenderService.get_instance()
    assert service is not None

    # Deterministic generation of 50 fixed test histories
    catalog_app_ids = service.catalog_app_ids
    if len(catalog_app_ids) < 20:
        pytest.skip("Catalog size too small for golden artifact test.")

    fixed_histories = []
    for i in range(50):
        # Deterministic pseudo-random history of 3 to 10 items
        step = (i % 7) + 1
        length = (i % 8) + 3
        hist = [int(catalog_app_ids[(i * step + j * 13) % len(catalog_app_ids)]) for j in range(length)]
        hist = list(dict.fromkeys(hist))  # remove duplicates
        fixed_histories.append(hist)

    fixture_path = Path(__file__).parent / "fixtures" / "golden_artifact_recommendations.json"
    fixture_path.parent.mkdir(parents=True, exist_ok=True)

    current_outputs = []
    for h in fixed_histories:
        rec_res = service.recommend(
            liked_app_ids=h,
            model_name="recsys_two_tower_clean",
            k=10,
            explain=False,
        )
        rec_ids = [it.app_id for it in rec_res.items]
        rec_scores = [it.score for it in rec_res.items]

        # Top-10 sanity invariants
        assert len(rec_ids) == 10
        assert len(set(rec_ids)) == 10  # no duplicates in top 10
        assert set(rec_ids).isdisjoint(set(h))  # seen items masked
        assert rec_scores == sorted(rec_scores, reverse=True)  # descending order

        current_outputs.append({
            "history": h,
            "recommended_app_ids": rec_ids,
        })

    # If fixture exists, assert exact stability
    if fixture_path.exists():
        expected_outputs = json.loads(fixture_path.read_text(encoding="utf-8"))
        assert len(current_outputs) == len(expected_outputs)
        for curr, exp in zip(current_outputs, expected_outputs, strict=True):
            assert curr["recommended_app_ids"] == exp["recommended_app_ids"], (
                f"Recommendations drifted for history {curr['history']}"
            )
    else:
        # Save fixture if first run
        fixture_path.write_text(json.dumps(current_outputs, indent=2), encoding="utf-8")
