def update_sprint_report(report_path: Path | str = "docs/results/SPRINT_REPORT.md") -> None:
    p = Path(report_path)
    orig = p.read_text(encoding="utf-8")
    auth_state = render_current_state(p.parent)

    title_prefix = "# SteamIQ: ML Evidence Hardening Sprint Report\n\n"
    history_sep = "# History (superseded, do not cite)"
    history_header = (
        "# History (superseded, do not cite)\n\n"
        "> [!WARNING]\n"
        "> Everything in this History section reflects preliminary sprints and intermediate iterations.\n"
        "> Numerical figures and provisional claims below are superseded by the **Current Authoritative State** above and must NOT be cited as current evidence.\n\n"
    )

    if history_sep in orig:
        parts = orig.split(history_sep, 1)
        hist_text = parts[1]
        warning_marker = "> Numerical figures and provisional claims below are superseded"
